// Build a flat lookup map: code -> sticker info
export const STICKER_MAP = {};

INTRO_STICKERS.forEach(s => {
  STICKER_MAP[s.code] = { ...s, team: "Intro / History", teamCode: "FWC" };
});

COCA_COLA_STICKERS.forEach(s => {
  STICKER_MAP[s.code] = { ...s, team: "Coca Cola", teamCode: "CC" };
});

TEAMS.forEach(team => {
  team.stickers.forEach(s => {
    const code = `${team.code}${s.n}`;
    STICKER_MAP[code] = { ...s, code, team: team.name, teamCode: team.code };
  });
});

// Get full sticker code from team code + number
export const getStickerCode = (teamCode, n) => `${teamCode}${n}`;

// Get all sticker codes for a team
export const getTeamStickerCodes = (teamCode) => {
  const team = TEAMS.find(t => t.code === teamCode);
  if (!team) return [];
  return team.stickers.map(s => `${teamCode}${s.n}`);
};

export default TEAMS;
